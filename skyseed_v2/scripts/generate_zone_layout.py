#!/usr/bin/env python3
"""Author a deterministic whole-globe rectangular Zone-layout YAML file."""

from __future__ import annotations

import argparse
from math import cos, radians
from pathlib import Path
import sys


PROJECT_ROOT = Path(__file__).resolve().parents[1]
SOURCE_ROOT = PROJECT_ROOT / "src"
if str(SOURCE_ROOT) not in sys.path:
    sys.path.insert(0, str(SOURCE_ROOT))

from skyseed_v2.configuration.simulator import (
    LatitudeLongitudeRectangleDefinition,
    ZoneDefinition,
    ZoneLayoutDefinition,
    load_zone_layout_definition,
)


_ALIGNMENTS = ("antimeridian-centered", "prime-meridian-centered")


def _canonical_longitude(value: float) -> float:
    canonical = (value + 180.0) % 360.0 - 180.0
    return 0.0 if canonical == 0.0 else canonical


def _number(value: float) -> str:
    if value == 0.0:
        value = 0.0
    result = f"{value:.12f}".rstrip("0").rstrip(".")
    return f"{result}.0" if "." not in result else result


def _longitude_number(value: float) -> str:
    result = repr(_canonical_longitude(value))
    return f"{result}.0" if "." not in result else result


def build_global_zone_layout(
    *,
    latitude_bands: int,
    equatorial_cells: int,
    alignment: str,
) -> ZoneLayoutDefinition:
    """Construct a validated cosine-scaled whole-globe grid definition."""

    if isinstance(latitude_bands, bool) or not isinstance(latitude_bands, int):
        raise TypeError("latitude_bands must be an integer")
    if latitude_bands <= 0:
        raise ValueError("latitude_bands must be positive")
    if isinstance(equatorial_cells, bool) or not isinstance(
        equatorial_cells, int
    ):
        raise TypeError("equatorial_cells must be an integer")
    if equatorial_cells <= 0:
        raise ValueError("equatorial_cells must be positive")
    if alignment not in _ALIGNMENTS:
        raise ValueError(f"alignment must be one of {_ALIGNMENTS!r}")

    latitude_height = 180.0 / latitude_bands
    alignment_center = -180.0 if alignment == "antimeridian-centered" else 0.0
    zones = []
    for band_index in range(latitude_bands):
        south = -90.0 + latitude_height * band_index
        north = -90.0 + latitude_height * (band_index + 1)
        midpoint = (south + north) / 2.0
        longitude_count = max(
            1,
            round(equatorial_cells * cos(radians(midpoint))),
        )
        boundaries = tuple(
            _canonical_longitude(
                alignment_center
                + 360.0 * (boundary_index + 0.5) / longitude_count
            )
            for boundary_index in range(longitude_count)
        )
        for cell_index in range(longitude_count):
            zones.append(
                ZoneDefinition(
                    zone_id=f"zone-b{band_index:02d}-c{cell_index:03d}",
                    priority=0,
                    geometry=LatitudeLongitudeRectangleDefinition(
                        south_latitude_deg=south,
                        north_latitude_deg=north,
                        west_longitude_deg=boundaries[cell_index - 1],
                        east_longitude_deg=boundaries[cell_index],
                    ),
                )
            )
    return ZoneLayoutDefinition(zones=tuple(zones), allow_overlap=False)


def render_zone_layout(
    layout: ZoneLayoutDefinition,
    *,
    latitude_bands: int,
    equatorial_cells: int,
    alignment: str,
) -> str:
    """Render one already-validated definition with a stable YAML format."""

    if not isinstance(layout, ZoneLayoutDefinition):
        raise TypeError("layout must be a ZoneLayoutDefinition")
    lines = [
        "# Generated by scripts/generate_zone_layout.py.",
        (
            f"# {latitude_bands} whole-globe latitude bands; longitude cell "
            "counts follow"
        ),
        (
            "# max(1, round("
            f"{equatorial_cells} * cos(radians(latitude-band midpoint))))."
        ),
        f"# Alignment: {alignment}.",
        "allow_overlap: false",
        "zones:",
    ]
    for zone in layout.zones:
        geometry = zone.geometry
        lines.extend(
            (
                f"  - zone_id: {zone.zone_id}",
                "    geometry:",
                "      kind: latitude-longitude-rectangle",
                (
                    "      south_latitude_deg: "
                    f"{_number(geometry.south_latitude_deg)}"
                ),
                (
                    "      north_latitude_deg: "
                    f"{_number(geometry.north_latitude_deg)}"
                ),
                (
                    "      west_longitude_deg: "
                    f"{_longitude_number(geometry.west_longitude_deg)}"
                ),
                (
                    "      east_longitude_deg: "
                    f"{_longitude_number(geometry.east_longitude_deg)}"
                ),
            )
        )
    return "\n".join(lines) + "\n"


def _canonical_content(
    *, latitude_bands: int, equatorial_cells: int, alignment: str
) -> tuple[ZoneLayoutDefinition, str]:
    layout = build_global_zone_layout(
        latitude_bands=latitude_bands,
        equatorial_cells=equatorial_cells,
        alignment=alignment,
    )
    return layout, render_zone_layout(
        layout,
        latitude_bands=latitude_bands,
        equatorial_cells=equatorial_cells,
        alignment=alignment,
    )


def _write_atomic(path: Path, content: str) -> None:
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_name(f".{destination.name}.tmp")
    try:
        temporary.write_text(content, encoding="utf-8")
        temporary.replace(destination)
    finally:
        temporary.unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--latitude-bands", type=int, required=True)
    parser.add_argument("--equatorial-cells", type=int, required=True)
    parser.add_argument("--alignment", choices=_ALIGNMENTS, required=True)
    destination = parser.add_mutually_exclusive_group(required=True)
    destination.add_argument("--output", type=Path)
    destination.add_argument(
        "--check",
        type=Path,
        metavar="EXISTING_YAML",
        help="verify an existing file without modifying it",
    )
    arguments = parser.parse_args(argv)

    try:
        layout, content = _canonical_content(
            latitude_bands=arguments.latitude_bands,
            equatorial_cells=arguments.equatorial_cells,
            alignment=arguments.alignment,
        )
    except (TypeError, ValueError) as error:
        parser.error(str(error))

    if arguments.check is not None:
        existing = load_zone_layout_definition(arguments.check)
        if existing != layout:
            parser.error(f"{arguments.check} does not match the requested grid")
        if arguments.check.read_text(encoding="utf-8") != content:
            parser.error(
                f"{arguments.check} is semantically equal but not canonically formatted"
            )
        print(f"PASS: {arguments.check} matches {len(layout.zones)} Zones")
        return 0

    assert arguments.output is not None
    _write_atomic(arguments.output, content)
    print(f"Wrote {len(layout.zones)} Zones to {arguments.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
