#!/usr/bin/env python3
"""Refresh the frozen S4 GroundStation YAML from reviewed research evidence."""

from __future__ import annotations

import argparse
from hashlib import sha256
import json
from pathlib import Path
from typing import Any


PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = (
    PROJECT_ROOT / "examples/s4_satellite_internet/ground_stations.yaml"
)
REVIEWED_EVIDENCE_COUNT = 358
FROZEN_GROUND_STATION_COUNT = 355
REVIEWED_EVIDENCE_SHA256 = (
    "c606d31ae7ec28f714886fdc8c534f52dac69c494f682ee38756fc4abeb5df1e"
)


def _quoted(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _number(value: float) -> str:
    if value == 0.0:
        value = 0.0
    result = f"{value:.12f}".rstrip("0").rstrip(".")
    return f"{result}.0" if "." not in result else result


def load_reviewed_sites(source: Path) -> tuple[dict[str, Any], ...]:
    """Validate the exact reviewed source and select its frozen S4 records."""

    content = Path(source).read_bytes()
    digest = sha256(content).hexdigest()
    if digest != REVIEWED_EVIDENCE_SHA256:
        raise ValueError(
            "reviewed GroundStation evidence SHA-256 mismatch: "
            f"expected {REVIEWED_EVIDENCE_SHA256}, got {digest}"
        )
    payload = json.loads(content)
    if (
        not isinstance(payload, dict)
        or payload.get("record_type")
        != "skyseed-external-ground-station-evidence"
        or payload.get("record_version") != 1
    ):
        raise ValueError("reviewed GroundStation evidence root is unexpected")
    records = payload.get("sites")
    if not isinstance(records, list) or len(records) != REVIEWED_EVIDENCE_COUNT:
        raise ValueError("reviewed GroundStation evidence must contain 358 sites")
    selected = [
        record
        for record in records
        if isinstance(record, dict)
        and record.get("included_in_proposed_benchmark") is True
    ]
    if len(selected) != FROZEN_GROUND_STATION_COUNT:
        raise ValueError("reviewed GroundStation selection must contain 355 sites")
    if payload.get("proposed_benchmark", {}).get("site_count") != len(selected):
        raise ValueError("reviewed GroundStation selection count is inconsistent")

    identities = [record.get("research_id") for record in selected]
    if any(not isinstance(value, str) or not value for value in identities):
        raise ValueError("reviewed GroundStation IDs must be non-empty strings")
    if len(set(identities)) != len(identities):
        raise ValueError("reviewed GroundStation selection has duplicate IDs")
    for record in selected:
        names = record.get("names")
        latitude = record.get("latitude_deg")
        longitude = record.get("longitude_deg")
        if (
            not isinstance(names, list)
            or not names
            or any(not isinstance(name, str) or not name for name in names)
        ):
            raise ValueError("reviewed GroundStation names are unexpected")
        if (
            isinstance(latitude, bool)
            or not isinstance(latitude, (int, float))
            or not -90.0 <= latitude <= 90.0
        ):
            raise ValueError("reviewed GroundStation latitude is unexpected")
        if (
            isinstance(longitude, bool)
            or not isinstance(longitude, (int, float))
            or not -180.0 <= longitude <= 180.0
        ):
            raise ValueError("reviewed GroundStation longitude is unexpected")
        if record.get("coordinate_evidence_class") not in {"A", "B", "C", "D"}:
            raise ValueError("reviewed GroundStation evidence class is unexpected")
        if not {"Ka", "E"}.intersection(record.get("bands", ())):
            raise ValueError("reviewed GroundStation has no supported gateway band")
        if record.get("operational_status") not in {
            "current",
            "historical",
            "planned",
        }:
            raise ValueError("reviewed GroundStation status is unexpected")
    return tuple(sorted(selected, key=lambda record: record["research_id"]))


def _display_name(record: dict[str, Any]) -> str:
    names = record["names"]
    name = max(names, key=lambda value: ("," in value, len(value), value))
    if "," not in name:
        name = f"{name}, {record['country_or_territory']}"
    return f"Starlink Gateway - {name}"


def render_ground_stations(source: Path) -> str:
    """Render the exact checked S4 schema from the reviewed selection."""

    records = load_reviewed_sites(source)
    lines = [
        "# Generated by scripts/refresh_s4_ground_stations.py.",
        "# Frozen from the reviewed 2026-08-25 research evidence selection.",
        f"# Research source SHA-256: {REVIEWED_EVIDENCE_SHA256}",
        "# Includes supported current, planned, and historical Ka/E gateway sites.",
        "# This is benchmark geometry, not a simultaneous operational snapshot.",
        "schema_version: skyseed-ground-stations/v1",
        "ground_stations:",
    ]
    for record in records:
        lines.extend(
            (
                f"  - ground_station_id: {record['research_id']}",
                f"    display_name: {_quoted(_display_name(record))}",
                f"    latitude_deg: {_number(float(record['latitude_deg']))}",
                f"    longitude_deg: {_number(float(record['longitude_deg']))}",
                "    elevation_m: 0.0",
                "    operator: null",
                "    station_type: gateway",
            )
        )
    return "\n".join(lines) + "\n"


def _write_atomic(path: Path, content: str) -> None:
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_name(f".{destination.name}.tmp")
    try:
        temporary.write_text(content, encoding="utf-8")
        temporary.replace(destination)
    finally:
        temporary.unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--research-source", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true")
    action.add_argument("--check", action="store_true")
    arguments = parser.parse_args(argv)

    try:
        content = render_ground_stations(arguments.research_source)
    except (OSError, ValueError, json.JSONDecodeError) as error:
        parser.error(str(error))
    if arguments.check:
        if arguments.output.read_text(encoding="utf-8") != content:
            parser.error(f"{arguments.output} differs from reviewed evidence")
        print(f"PASS: {arguments.output} contains {FROZEN_GROUND_STATION_COUNT} sites")
        return 0
    _write_atomic(arguments.output, content)
    print(
        f"Wrote {FROZEN_GROUND_STATION_COUNT} GroundStations to {arguments.output}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
